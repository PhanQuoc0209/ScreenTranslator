/**
 * Get irregular candidates for a normalized word.
 * @param {string} word Lowercase word.
 * @returns {Array<{ lemma: string, pos: string, category: string }> | null}
 */
function getIrregularCandidates(word) {
  if (!word || typeof word !== 'string') return null;
  const entries = IRREGULAR_FORMS[word.toLowerCase()];
  return entries ? [...entries] : null;
}

/**
 * Check if a word is recognized as an irregular inflected form.
 * @param {string} word
 * @returns {boolean}
 */
function isIrregularForm(word) {
  if (!word || typeof word !== 'string') return false;
  return Object.prototype.hasOwnProperty.call(IRREGULAR_FORMS, word.toLowerCase());
}

/**
 * Total count of registered irregular surface forms.
 */
function getIrregularCount() {
  return Object.keys(IRREGULAR_FORMS).length;
}

